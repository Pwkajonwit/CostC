-- 6. HIGH-SPEED METRICS RPC FUNCTION
-- =========================================================================
CREATE OR REPLACE FUNCTION get_dashboard_metrics()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    result JSONB;
    v_total_bills BIGINT;
    v_total_amount NUMERIC;
    v_total_projects BIGINT;
    v_pending_bills BIGINT;
BEGIN
    SELECT 
        COUNT(*),
        COALESCE(SUM(amount), 0),
        COUNT(CASE WHEN status = 'ตั้งเบิก' OR status = 'รอตั้งเบิก' OR status = 'รออนุมัติ' THEN 1 END)
    INTO v_total_bills, v_total_amount, v_pending_bills
    FROM public.bills;

    SELECT COUNT(*) INTO v_total_projects FROM public.projects;

    result := jsonb_build_object(
