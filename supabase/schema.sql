-- 8. AUTOMATED BACKFILL FROM LEGACY JSONB
-- =========================================================================
DO $$
DECLARE
    v_data JSONB;
    v_key TEXT;
    v_val JSONB;
    v_num_id BIGINT;
    v_rec_date DATE;
    v_wht_date DATE;
    v_paid_date DATE;
BEGIN
    SELECT data INTO v_data FROM public.system_options WHERE id = 'bill_follow_dates';
    IF v_data IS NOT NULL AND jsonb_typeof(v_data) = 'object' THEN
        FOR v_key, v_val IN SELECT * FROM jsonb_each(v_data)
        LOOP
            BEGIN
                IF v_key ~ '^[0-9]+$' THEN
                    v_num_id := v_key::BIGINT;
                    v_rec_date := CASE WHEN (v_val->>'วันได้บิล') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN (v_val->>'วันได้บิล')::DATE ELSE NULL END;
                    v_wht_date := CASE WHEN (v_val->>'วันออก 3%') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN (v_val->>'วันออก 3%')::DATE ELSE NULL END;
                    v_paid_date := CASE WHEN (v_val->>'วันจ่าย') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN (v_val->>'วันจ่าย')::DATE ELSE NULL END;

                    UPDATE public.bills
                    SET 
                        bill_received_date = COALESCE(bills.bill_received_date, v_rec_date),
                        wht_issued_date = COALESCE(bills.wht_issued_date, v_wht_date),
                        paid_date = COALESCE(bills.paid_date, v_paid_date),
                        labor_status = COALESCE(bills.labor_status, v_val->>'statusค่าแรง'),
                        created_by = COALESCE(bills.created_by, v_val->>'ผู้สร้างบิล', v_val->>'created_by')
                    WHERE id = v_num_id;
                END IF;
            EXCEPTION WHEN OTHERS THEN
                NULL;
            END;
        END LOOP;
    END IF;
END $$;

